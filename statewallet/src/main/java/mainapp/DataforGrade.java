package mainapp;

import java.util.Scanner;

/**
 * Παρέχει τα δεδομένα για την βαθμολόγηση του κράτους ανά έτος.
 */
public final class DataforGrade {

    /** Πίνακας με τα διαθέσιμα έτη. */
    private static final int[] YEARS = {
        2018, 2019, 2020, 2021, 2022, 2023, 2024, 2025
    };

    /** Πίνακας δεδομένων ανά έτος. */
    private static final double[][] DATA = {
        // 2018
        {0.019, 142.5, 0.04, 0.22, 0.17,
         -0.02, 33.5, 0.08, 0.16, -0.01},
        // 2019
        {0.021, 140.2, 0.038, 0.24, 0.19,
         -0.03, 32.8, 0.085, 0.165, -0.015},
        // 2020
        {-0.085, 160.5, -0.06, 0.26, 0.20,
         -0.08, 34.0, 0.09, 0.19, 0.02},
        // 2021
        {0.075, 155.0, -0.02, 0.28, 0.22,
         0.05, 33.2, 0.092, 0.18, 0.01},
        // 2022
        {0.056, 148.0, 0.001, 0.30, 0.24,
         -0.01, 32.5, 0.095, 0.175, 0.005},
        // 2023
        {0.023, 142.0, 0.015, 0.32, 0.26,
         -0.025, 31.8, 0.098, 0.17, -0.02},
        // 2024
        {0.025, 138.0, 0.022, 0.34, 0.28,
         -0.03, 31.2, 0.10, 0.165, -0.025},
        // 2025
        {0.028, 135.0, 0.028, 0.36, 0.30,
         -0.035, 30.5, 0.105, 0.16, -0.03}
    };

    /**
     * Επιστρέφει τα δεδομένα για ένα συγκεκριμένο έτος.
     *
     * @param year Το έτος.
     * @return Πίνακας με τα δεδομένα του έτους.
     */
    public double[] getData(final int year) {
        for (int i = 0; i < YEARS.length; i++) {
            if (YEARS[i] == year) {
                return DATA[i];
            }
        }
        return new double[0];
    }

    /**
     * Ζητάει από τον χρήστη να επιλέξει ένα έτος.
     *
     * @return Το επιλεγμένο έτος.
     */
    public int chooseYear() {
        Scanner scan = new Scanner(System.in, "CP737");
        int year;
        boolean flag = false;
        do {
            System.out.println("Εισάγετε το έτος για το οποίο θέλετε "
                    + "να δείτε τον βαθμό");
            year = scan.nextInt();
            // Magic Numbers αντικαταστάθηκαν με YEARS[0] και YEARS[length-1]
            if (year < YEARS[0] || year > YEARS[YEARS.length - 1]) {
                System.out.println("Δεν υπάρχουν διαθέσιμα στοιχεία για "
                        + "αυτό το έτος. Τα διαθέσιμα έτη είναι από το "
                        + YEARS[0] + " έως το "
                        + YEARS[YEARS.length - 1]);
            } else {
                flag = true;
            }
        } while (!flag);
        return year;
    }
}
