package mainapp;

/**
 * Παρέχει λεκτικές περιγραφές και σχόλια για τους βαθμούς που έχουν
 * υπολογιστεί.
 */
public final class GradeChar {

    // Σταθερές Βαθμών
    /** Βαθμός 5 (Πολύ χαμηλά/Αποτυχία). */
    private static final int GRADE_LOWEST = 5;
    /** Βαθμός 6 (Χαμηλά). */
    private static final int GRADE_LOW = 6;
    /** Βαθμός 8 (Καλά). */
    private static final int GRADE_GOOD = 8;
    /** Βαθμός 9 (Πολύ καλά/Άριστα). */
    private static final int GRADE_EXCELLENT = 9;

    /**
     * Εκτυπώνει σχόλια για τον βαθμό μεγέθυνσης του ΑΕΠ.
     *
     * @param grade Ο βαθμός (5-10).
     */
    public void gdpGrowthChar(final int grade) {
        if (grade == GRADE_LOWEST) {
            System.out.println("Το ΑΕΠ μειώθηκε! Πρέπει να "
                    + " γίνουν ενέργειες για την επαναφορά της ανάπτυξής του "
                    + " το νέο έτος");
        } else if (grade == GRADE_LOW) {
            System.out.println("Πολύ μικρή αύξηση του ΑΕΠ! Πρέπει την "
                    + "επόμενη χρονιά να αυξηθεί ο ρυθμός μεγένθυσης!");
        } else if (grade >= GRADE_EXCELLENT) {
            System.out.println("Μεγάλη αύξηση του ΑΕΠ! Η εγχώρια οικονομία"
                    + " αναπτύσσεται με γρήγορο ρυθμό. Συγχαρητήρια");
        } else {
            System.out.println("Καλή επίδοση. Το ΑΕΠ παρουσίασε "
                    + "αποδεκτή αύξηση.");
        }
    }

    /**
     * Εκτυπώνει σχόλια για τον βαθμό του πρωτογενούς πλεονάσματος.
     *
     * @param grade Ο βαθμός (5-10).
     */
    public void surplusChar(final int grade) {
        if (grade == GRADE_LOWEST) {
            System.out.println("Το πρωτογενές πλεόνασμα έχει αρνητική τιμή."
                    + " Το κράτος δεν κατάφερε να καλύψει τα έξοδά του "
                    + "με τα έσοδα! Πρέπει να γίνει πιο υπεύθυνη κατανομή "
                    + "και διάθεση των πόρων τη νέα χρονιά!");
        } else if (grade == GRADE_LOW) {
            System.out.println("Μικρό πρωτογενές πλεόνασμα. Πρέπει να γίνουν "
                    + "ενέργειες για την αύξησή του ");
        } else if (grade >= GRADE_EXCELLENT) {
            System.out.println("Το κράτος κατάφερε να καλύψει τα έξοδά του με "
                    + " τα έσοδά του εξαιρούμενων των τόκων πολύ αποδοτικά! "
                    + " Συγχαρητήρια");
        } else {
            System.out.println("Καλή επίδοση. Το κράτος κάλυψε τα έξοδά του"
                    + " με τα έσοδα που είχε σε αποδεκτό βαθμό.");
        }
    }

    /**
     * Εκτυπώνει σχόλια για τον βαθμό του δείκτη GINI (ανισότητα).
     *
     * @param grade Ο βαθμός (5-10).
     */
    public void giniChar(final int grade) {
        if (grade <= GRADE_LOW) {
            System.out.println("Υπάρχουν μεγάλες εισοδηματικές ανισότητες"
                    + " εντός του πληθυσμού! Πρέπει να γίνουν ενέργειες "
                    + "για να κατανεμηθεί πιο δίκαια το συνολικό εισόδημα "
                    + "στην κοινωνία!");
        } else if (grade >= GRADE_EXCELLENT) {
            System.out.println("Οι εισοδηματικές ανισότητες έχουν "
                    + "περιοριστεί! Πολύ καλή επίδοση!");
        } else {
            System.out.println("Aποδεκτή επίδοση. Οι εισοδηματικές "
                    + "ανισότητες βρίσκονται σε επιτρεπτό επίπεδο.");
        }
    }

    /**
     * Εκτυπώνει σχόλια για τον βαθμό εγκληματικότητας.
     *
     * @param grade Ο βαθμός (5-10).
     */
    public void crimeRateChar(final int grade) {
        if (grade <= GRADE_LOW) {
            System.out.println("Μεγάλη αύξηση της εγκληματικότητας! "
                    + "Πρέπει να γίνουν ενέργειες για τον περιορισμό της");
        } else if (grade >= GRADE_EXCELLENT) {
            System.out.println("H εγκληματικότητα μειώθηκε σημαντικά! "
                    + "Πολύ καλή επίδοση. Συγχαρητήρια!");
        } else {
            System.out.println("Οι μεταβολές της εγκληματικότητας βρίσκονται "
                    + "εντός των επιτρεπτών ορίων.");
        }
    }

    /**
     * Εκτυπώνει σχόλια για τον βαθμό δαπανών Υγείας και Παιδείας.
     *
     * @param grade Ο βαθμός (5-10).
     */
    public void edHealthChar(final int grade) {
        if (grade <= GRADE_LOW) {
            System.out.println("Oι δαπάνες στην υγεία και την παιδεία "
                    + "είναι αρκετά χαμηλές. Πρέπει να αυξηθούν! Υπάρχει "
                    + "δυσαρέσκεια στον πληθυσμό!");
        } else if (grade >= GRADE_EXCELLENT) {
            System.out.println("Γίνονται μεγάλες δαπάνες σε υγεία "
                    + "και παιδεία! Οι πολίτες είναι ευχαριστημένοι!");
        } else {
            System.out.println("Οι δαπάνες σε υγεία και παιδεία βρίσκονται "
                    + "σε επιτρεπτό επίπεδο. Ίσως πρέπει να αυξηθούν για την "
                    + "ευρύτερη ικανοποίηση των πολιτών!");
        }
    }

    /**
     * Εκτυπώνει σχόλια για τον βαθμό Ανανεώσιμων Πηγών Ενέργειας (RES).
     *
     * @param grade Ο βαθμός (5-10).
     */
    public void resChar(final int grade) {
        if (grade <= GRADE_LOW) {
            System.out.println("Το ποσοστό χρήσης των ανανεώσιμων "
                    + "πηγών ενέργειας είναι χαμηλό! Πρέπει να αυξηθεί.");
        } else if (grade >= GRADE_EXCELLENT) {
            System.out.println("Οι ανανεώσιμες πηγές ενέργειας "
                    + "αξιοποιήθηκαν σε πολύ μεγάλη κλίμακα! Συγχαρητήρια!");
        } else {
            System.out.println("Η αξιοποίηση ανανεώσιμων πηγών ενέργειας "
                    + " βρίσκεται σε αποδεκτό επίπεδο");
        }
    }

    /**
     * Εκτυπώνει σχόλια για τον βαθμό εκπομπής ρύπων.
     *
     * @param grade Ο βαθμός (5-10).
     */
    public void emissionChar(final int grade) {
        if (grade <= GRADE_LOW) {
            System.out.println("Οι ρύποι παρουσίασαν σημαντική αύξηση. "
                    + " Πρέπει να γίνουν ενέργειες για την μείωσή τους ώστε να"
                    + " πετύχουμε τους μακροπρόθεσμους περιβαλλοντικούς "
                    + "μας στόχους!");
        } else if (grade >= GRADE_EXCELLENT) {
            System.out.println("Αξιοσημείωτη μείωση στους ρύπους! "
                    + "Συγχαρητήρια.");
        } else if (grade == GRADE_GOOD) {
            System.out.println("Μικρή μείωση των ρύπων. Καλή επίδοση με βάση"
                    + " τους μακροπρόθεσμους στόχους.");
        } else {
            System.out.println("Μικρή αύξηση στους ρύπους. Μπορούν να γίνουν "
                    + "ενέργειες για να φτάσουμε στην μείωση!");
        }
    }
}
